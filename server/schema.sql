-- SafeRoute UA schema for plain Postgres (Cloud SQL). Same tables and indexes as the Supabase project
-- qiupznnfixzimxmovuei, minus Supabase's roles and RLS: only the API's own login touches these tables.
create extension if not exists pgcrypto;

create table if not exists alerts (
  id              uuid primary key default gen_random_uuid(),
  alert_id        text not null,
  region_id       text,
  alert_type      text not null,
  start_time      timestamptz not null,
  end_time        timestamptz,
  location_name   text not null,
  location_oblast text not null,
  location_raion  text,
  coordinates     point,
  severity        text,
  notes           text,
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists idx_alerts_alert_id on alerts (alert_id);
create index if not exists idx_alerts_alert_type on alerts (alert_type);
create index if not exists idx_alerts_location_oblast on alerts (location_oblast);
create index if not exists idx_alerts_severity on alerts (severity);
create index if not exists idx_alerts_start_time on alerts (start_time);
create index if not exists idx_alerts_time_location on alerts (start_time, location_oblast);

create table if not exists site_visits (
  id         bigint generated by default as identity primary key,
  visited_at timestamptz not null default now(),
  path       text,
  language   text
);
